def test_budget_timeout_publishes_degraded_sample_and_exit_one() -> None:
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        slow = root / "slow.py"
        child_pid = root / "slow-child.pid"
        _write_python(
            slow,
            "import pathlib, subprocess, sys, time\n"
            "child = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(2)'])\n"
            f"pathlib.Path({str(child_pid)!r}).write_text(str(child.pid), encoding='utf-8')\n"
            "time.sleep(2)\n",
        )
        output = root / "fleet-data.js"
        err = io.StringIO()

        began = time.monotonic()
        with contextlib.redirect_stderr(err):
            code = producer.run_tick(
                "fleet",
                output=output,
                lock_dir=root / "locks",
                producer_script=slow,
                budget_s=0.5,
                interval_s=75,
            )
        elapsed = time.monotonic() - began

        assert code == 1
        assert elapsed < 1.5, f"budget failed to stop slow child: {elapsed:.3f}s"
        payload = _script_payload(output, "GF_FLEET")
        assert payload["last_success_at"] is None
        assert payload["incomplete"] is True
        assert payload["cadence_seconds"] == 75
        assert str(payload["last_error"]).startswith("budget:TimeoutExpired")
        assert "fleet-console-fleet-launchd.log" in str(payload["last_error"])
        assert "install-fleet-console.sh --status --plane fleet" in str(payload["last_error"])
        assert payload["registry_deep_sampled"] == 0
        assert payload["registry_total"] is None
        assert payload["projects"] == []
        assert "budget exhausted" in err.getvalue()
        assert "DEGRADED" in err.getvalue()

        assert child_pid.exists(), "slow sampler never started its descendant"
        descendant = int(child_pid.read_text(encoding="utf-8"))
        deadline = time.monotonic() + 0.5
        while time.monotonic() < deadline:
            try:
                os.kill(descendant, 0)
            except ProcessLookupError:
                break
            time.sleep(0.01)
        else:
            raise AssertionError(f"budget left descendant process {descendant} alive")

        # The timed-out path must release its lock after publishing the sample.
        after = producer.PlaneLock(root / "locks", "fleet")
        assert after.acquire()
        after.release()


