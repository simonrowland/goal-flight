def test_second_tick_refuses_held_plane_lock_visibly() -> None:
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        ready = root / "holder-ready"
        slow = root / "slow-holder.py"
        _write_python(
            slow,
            "import pathlib, time\n"
            f"pathlib.Path({str(ready)!r}).write_text('ready', encoding='utf-8')\n"
            "time.sleep(0.5)\n"
            + _healthy_sampler_body("lock-holder-success"),
        )
        holder_code = (
            "import pathlib, sys; "
            f"sys.path.insert(0, {str(ROOT / 'scripts')!r}); "
            "import goalflight_fleet_console_producer as producer; "
            "raise SystemExit(producer.run_tick("
            f"'fleet', output=pathlib.Path({str(root / 'holder.js')!r}), "
            f"lock_dir=pathlib.Path({str(root / 'locks')!r}), "
            f"producer_script=pathlib.Path({str(slow)!r}), budget_s=1.0))"
        )
        holder = subprocess.Popen([sys.executable, "-c", holder_code])
        deadline = time.monotonic() + 2
        while not ready.exists() and time.monotonic() < deadline:
            time.sleep(0.01)
        assert ready.exists(), "first tick never reached its locked producer"
        err = io.StringIO()
        try:
            with contextlib.redirect_stderr(err):
                code = producer.run_tick(
                    "fleet",
                    output=root / "never-written.js",
                    lock_dir=root / "locks",
                    producer_script=root / "must-not-run.py",
                    budget_s=0.1,
                )
        finally:
            holder.wait(timeout=2)

        assert holder.returncode == 0
        assert code == producer.EXIT_OVERLAP
        assert "SKIPPED: overlap lock held" in err.getvalue()
        assert "fleet" in err.getvalue()
        assert not (root / "never-written.js").exists()


def test_plane_locks_are_independent() -> None:
    with tempfile.TemporaryDirectory() as td:
        root = Path(td)
        quick = root / "quick.py"
        _write_python(quick, _healthy_sampler_body("independent-plane-success"))

        fleet_holder = producer.PlaneLock(root / "locks", "fleet")
        assert fleet_holder.acquire()
        try:
            assert producer.run_tick(
                "attention",
                output=root / "attention.js",
                lock_dir=root / "locks",
                producer_script=quick,
                budget_s=0.5,
            ) == 0
        finally:
            fleet_holder.release()

